package com.example.aicodebackend.constant;

public interface ChatHistoryConstant {

    /**
     * 生成被中断（用户离开页面/关闭连接）时，写入对话历史的标记前缀
     * <p>
     * 客户端断开时服务端侧的工具调用可能已经落盘，但流不会正常完成，
     * 如果不落库就会出现"磁盘上有代码、对话历史里没有任何 AI 回复"的不一致。
     * 这里把已累积的内容按"中断"语义保存，并在开头加一个明确标记，
     * 让用户回到页面时能看到"这一轮生成到一半被中断了"，同时保证后续对话的上下文不丢。
     */
    String INTERRUPTED_MARKER = "⚠️ [生成已中断] 用户中途离开了页面，以下是已经生成的部分内容：\n\n";

    /**
     * 每次加载的对话历史条数（类似聊天软件的消息加载机制，每次加载最新 10 条）
     */
    long DEFAULT_PAGE_SIZE = 10;

    /**
     * 单次最多加载的对话历史条数
     */
    long MAX_PAGE_SIZE = 20;

    /**
     * 对话记忆中最多保留的消息条数（同时也是对话记忆初始化时最多加载的历史消息条数）
     */
    int MEMORY_MAX_MESSAGES = 50;

    /**
     * 单条消息落库的安全上限（字符数）
     * <p>
     * 只用于防止异常巨大的模型输出撑爆 message 字段（MEDIUMTEXT）导致插入失败，正常业务不会触发。
     * 注意：对话历史会完整展示给用户，因此落库时<b>不做</b>内容层面的截断；
     * 控制模型上下文长度的压缩统一放在加载对话记忆时进行。
     */
    int MESSAGE_MAX_LENGTH = 1_000_000;

    /**
     * 加载对话记忆时，单个 Markdown 代码块保留的最大字符数
     * <p>
     * 进入模型上下文的只有代码块的头部预览，代码块之外的说明文字、文件路径等原样保留。
     */
    int MEMORY_CODE_BLOCK_MAX_LENGTH = 200;

    /**
     * 加载对话记忆时单条消息保留的最大字符数
     * <p>
     * 兜底限制：即使按代码块压缩后仍然过长（例如一条消息里写了几十个文件），也只保留头部。
     */
    int MEMORY_MESSAGE_MAX_LENGTH = 6000;
}
